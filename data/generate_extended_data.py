"""
Synthetic extended realized-variance data for Exp5.

Generates aligned series of:
  - ``rv``      : daily realized variance (same as Oxford-Man synthetic data)
  - ``rs_neg``  : negative realized semivariance (RS-)
  - ``delta_j`` : signed jump variation (RS+ − RS-)

Data-generating process for RS-
--------------------------------
For each ticker the RV series is obtained from
:func:`data.generate_data.load_oxford_man_data`.  RS- is then modelled as::

    rs_neg_t = clip(0.40 * rv_t + ε_t,  0.01 * rv_t,  0.99 * rv_t)
    ε_t ~ N(0, (0.05 * rv_t)²)

so that RS- ≈ 0.40 × RV on average (always strictly positive).  The signed
jump variation follows from the RS+/RS- identity::

    delta_j_t = RS+_t − RS-_t = rv_t − 2 × rs_neg_t

All noise is drawn from a single ``numpy.random.default_rng(seed=2024)``
instance shared across tickers, ensuring global reproducibility.
"""

from __future__ import annotations

from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from data.generate_data import load_oxford_man_data

_GLOBAL_SEED = 2024


def load_extended_data(
    tickers: List[str] = ("SPX", "FTSE", "DJI"),
    start: str = "2001-08-29",
    end: str = "2020-12-31",
    data_dir: Optional[str] = None,
) -> Dict[str, pd.DataFrame]:
    """
    Generate synthetic extended data (RV, RS-, ΔJ) for the given tickers.

    The RV series is generated by :func:`~data.generate_data.load_oxford_man_data`
    using its fixed per-ticker seeds.  The RS- noise is drawn from a single RNG
    seeded with ``2024`` so results are reproducible independently of ticker order.

    Parameters
    ----------
    tickers : list of str
        Asset identifiers (SPX, FTSE, DJI are pre-seeded).
    start : str
        First business day (inclusive).
    end : str
        Last business day (inclusive).
    data_dir : str or None
        Unused; kept for API symmetry.

    Returns
    -------
    dict
        Mapping ``ticker -> pd.DataFrame`` with columns
        ``['rv', 'rs_neg', 'delta_j']`` and a ``DatetimeIndex`` of business days.
    """
    rv_data = load_oxford_man_data(tickers=list(tickers), start=start, end=end, data_dir=data_dir)
    rng = np.random.default_rng(_GLOBAL_SEED)

    result: Dict[str, pd.DataFrame] = {}
    for ticker in tickers:
        rv_series = rv_data[ticker]
        rv = rv_series.values

        noise = rng.normal(0.0, 0.05 * rv)
        rs_neg = np.clip(0.40 * rv + noise, 0.01 * rv, 0.99 * rv)
        delta_j = rv - 2.0 * rs_neg  # RS+ - RS-

        result[ticker] = pd.DataFrame(
            {"rv": rv, "rs_neg": rs_neg, "delta_j": delta_j},
            index=rv_series.index,
        )

    return result
